"""G3.2 primitive: is there a direction that moves the PEAK without moving boost?

WHY THIS RUNS BEFORE THE CONTROLLER. G3.1 solved the target exactly on the 3 of 8 specs
where it could start, and failed to start on the other 5. The diagnosis was not the search:
it was that peak_in_band is the dominant refusal (7 against boost_range's 4) and the only
direction the system owns, d_boost, moves the peak and the boost together. Stepping against
d_boost to bring the peak back in band drives boost out of boost_range first, so the
feasible window along that single line is bounded at BOTH ends and 0 of 5 repairs succeeded.

A second coordinate is therefore the whole proposal, and the project's rule is that a
primitive gets measured before an architecture is built on it. The d_boost probe already
taught this lesson the expensive way: it was 97.8% accurate and still worthless, because a
free constant sign table scored 95.7% (p = 0.232) and the 31 measure_all per spec bought
nothing. So this probe asks the question that decides whether G3.2 can exist at all:

    for each of the six axes, what is d(peak_freq)/dx_i relative to d(boost)/dx_i?

If some axis moves the peak with markedly less boost coupling than d_boost does, that axis
is d_peak and the 2-D repair plane is real. If every axis moves both in lockstep, the plane
is degenerate, there is no second coordinate to have, and G3.2 should not be built.

The null is the same one that killed the first probe: a CONSTANT sign/selectivity table,
computed once, against a per-design probe. If the table is as good, the table is what the
controller gets, for free.

SECOND QUESTION, same run at no extra cost. 3 of 8 seed-3 specs had 0 of 5 guard-valid
stage-1 designs -- nothing to repair from and no metrics to steer by. Every point here
records the guard's own Check and reason on rejection, so "which constraint blocks repair"
is answered from data rather than guessed at when Stage A is designed.

Calibration runs on spec-seed 2, the same slice the d_boost probe used and disjoint from
the seed-3 specs any controller is tested on. Stage 1 is regenerated byte-identically to
hybrid_audit (k = 5, no reset). This is a calibration artifact, not a controller arm: it
spends no per-spec budget and produces no circuits.

Changes no threshold, bound, reward, model, or benchmark criterion.
"""
from __future__ import annotations

import dataclasses
import json
import os
from pathlib import Path

P = Path(os.environ.get("USERPROFILE") or Path.home()) / "silq-ngspice"
os.environ.setdefault("NGSPICE_LIBRARY_PATH", str(P / "Library" / "bin" / "ngspice{}.dll"))
os.environ.setdefault("SPICE_LIB_DIR", str(P / "Library" / "share" / "ngspice"))
os.environ.setdefault("PDK_ROOT", str(Path(os.environ.get("USERPROFILE") or Path.home()) / "pdk"))
os.environ["PATH"] = os.pathsep.join([str(P / "shim"), str(P / "Library" / "bin"), os.environ["PATH"]])
if hasattr(os, "add_dll_directory"):
    os.add_dll_directory(str(P / "Library" / "bin"))

import argparse
import numpy as np

from silq.circuits.ctle import ACTION_SPACE, decode_action
from silq.evaluator import build_evaluator
from silq.specs import DEFAULT_SPEC, hard_pass
from silq.experiments.target_audit import make_specs

DIMS = list(ACTION_SPACE.keys())

#: Same central-difference step the d_boost probe verified at, so the tables are comparable.
PROBE_H = 0.05
K = 5


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--model", default="results/seq_clean40k.zip")
    p.add_argument("--specs", type=int, default=8)
    p.add_argument("--spec-seed", type=int, default=2)
    p.add_argument("--out", default="results/g32_peak_probe.json")
    args = p.parse_args()

    specs = make_specs(32, args.spec_seed)[:args.specs]
    guards: dict[float, object] = {}
    n_sim = 0

    def guard_for(channel: float):
        if channel not in guards:
            guards[channel] = build_evaluator(DEFAULT_SPEC, corner="tt", fast=False,
                                              channel_loss_db=channel)
        return guards[channel]

    def evaluate(x, target, channel):
        """Records peak_freq_ghz alongside boost, and the guard's own words on rejection.

        The existing probe artifact cannot answer this file's question because it stored
        boost_db only; peak_freq_ghz was computed by metrics_from_acx and discarded.
        """
        nonlocal n_sim
        n_sim += 1
        dv = decode_action(np.asarray(x))
        spec = dataclasses.replace(DEFAULT_SPEC, target_boost_db=target,
                                   channel_loss_db=channel)
        try:
            v = guard_for(channel).evaluate(dv, vdd=spec.vdd_nominal)
        except Exception as e:
            return {"valid": False, "guard_check": "exception", "reason": repr(e)[:200]}
        if not v.is_valid:
            return {"valid": False, "guard_check": str(getattr(v.check, "value", v.check)),
                    "reason": str(v.reason)[:200]}
        m = v.unwrap()
        ok, checks = hard_pass(m, spec)
        return {"valid": True, "boost_db": float(m.boost_db),
                "peak_freq_ghz": float(m.peak_freq_ghz),
                "dc_gain_db": float(m.dc_gain_db), "loose_pass": bool(ok),
                "failing": [c for c, good in checks.items() if not good]}

    from stable_baselines3 import PPO
    from silq.envs.sequential_env import SequentialEqualizerEnv
    model = PPO.load(args.model)
    env = SequentialEqualizerEnv(fast=False, seed=123, guarded=False)

    def stage1(i, target, channel):
        """Byte-identical to hybrid_audit.stage1: k evals, NO reset on terminated."""
        env.reset(seed=1000 + i)
        env._target, env._channel = target, channel
        obs = env._obs(env._measure(env._x))
        recs = [evaluate(env._x, target, channel)]
        while len(recs) < K:
            a, _ = model.predict(obs, deterministic=True)
            obs, _, _term, _trunc, _ = env.step(a)
            recs.append(evaluate(env._x, target, channel))
        return np.array(env._x, dtype=np.float64), recs

    lo, hi = DEFAULT_SPEC.peak_freq_lo_ghz, DEFAULT_SPEC.peak_freq_hi_ghz
    print("G3.2 PEAK PROBE | %d specs, spec-seed %d | h=%.3f | band %.2f-%.2f GHz"
          % (len(specs), args.spec_seed, PROBE_H, lo, hi), flush=True)
    print("  asks: is there an axis that moves the peak with less boost coupling than "
          "d_boost?\n", flush=True)

    def write(complete: bool) -> None:
        Path(args.out).write_text(json.dumps(
            {"probe_h": PROBE_H, "k": K, "spec_seed": args.spec_seed, "model": args.model,
             "band_ghz": [lo, hi], "n_measure_all": n_sim, "complete": complete,
             "rows": rows}, indent=1))

    rows: list[dict] = []
    for i, (target, channel) in enumerate(specs):
        x0, s1 = stage1(i, target, channel)
        base = s1[-1]
        if not base["valid"]:
            # No baseline metrics means no difference to take. Recorded rather than
            # skipped silently, because how OFTEN this happens is one of the two questions.
            print("  spec %2d  handoff GUARD-INVALID (%s) -- no baseline, probe skipped"
                  % (i, base["guard_check"]), flush=True)
            rows.append({"spec": i, "target_boost_db": target, "channel_loss_db": channel,
                         "stage1": s1, "base": base, "dims": None})
            write(False)
            continue

        dims = {}
        for j, name in enumerate(DIMS):
            e = np.zeros(len(DIMS)); e[j] = 1.0
            pts = {}
            for tag, s in (("plus", +PROBE_H), ("minus", -PROBE_H)):
                xt = np.clip(x0 + s * e, 0.0, 1.0)
                pts[tag] = {"moved": float(abs(xt[j] - x0[j])),
                            **evaluate(xt, target, channel)}
            # Central difference where both ends survived the guard, one-sided otherwise.
            # A dimension with neither end valid contributes None rather than a zero,
            # because "no measurement" and "no sensitivity" are different facts and
            # averaging the second into a table would understate that axis.
            a, b = pts["plus"], pts["minus"]
            if a["valid"] and b["valid"]:
                span = max(a["moved"] + b["moved"], 1e-12)
                dpk = (a["peak_freq_ghz"] - b["peak_freq_ghz"]) / span
                dbo = (a["boost_db"] - b["boost_db"]) / span
                mode = "central"
            elif a["valid"] or b["valid"]:
                g, sgn = (a, 1.0) if a["valid"] else (b, -1.0)
                span = max(g["moved"], 1e-12)
                dpk = sgn * (g["peak_freq_ghz"] - base["peak_freq_ghz"]) / span
                dbo = sgn * (g["boost_db"] - base["boost_db"]) / span
                mode = "one-sided"
            else:
                dpk = dbo = None
                mode = "no valid probe point"
            dims[name] = {"mode": mode, "d_peak_ghz": dpk, "d_boost_db": dbo, "points": pts}

        rows.append({"spec": i, "target_boost_db": target, "channel_loss_db": channel,
                     "stage1": s1, "base": base, "dims": dims})
        print("  spec %2d  base boost %5.2f peak %.3f GHz%s" %
              (i, base["boost_db"], base["peak_freq_ghz"],
               "" if base["loose_pass"] else "  FAILS " + ",".join(base["failing"])),
              flush=True)
        for n, d in dims.items():
            if d["d_peak_ghz"] is None:
                print("      %-7s no valid probe point" % n, flush=True)
                continue
            print("      %-7s dpeak %+9.3f GHz/unit   dboost %+8.2f dB/unit   %s"
                  % (n, d["d_peak_ghz"], d["d_boost_db"], d["mode"]), flush=True)
        write(False)

    write(True)
    print("\n%d measure_all spent (calibration, not a controller arm)" % n_sim, flush=True)
    print("wrote", args.out, flush=True)


if __name__ == "__main__":
    main()
